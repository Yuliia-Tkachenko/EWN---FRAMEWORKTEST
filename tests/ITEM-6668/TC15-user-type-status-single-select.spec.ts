import { test, type Page, type BrowserContext } from '@playwright/test';
import { LoginPage } from '../../pages/LoginPage';
import { LoginStatisticsReportPage } from '../../pages/reports/LoginStatisticsReportPage';
import { TestConfig } from '../../test.config';

test.describe.configure({ mode: 'serial' });

let page: Page;
let context: BrowserContext;

test.describe('TC15 — User Type and User Status are single-select dropdowns', () => {
  test.beforeAll(async ({ browser }) => {
    const config = new TestConfig();
    context = await browser.newContext();
    page = await context.newPage();
    const loginPage = new LoginPage(page);
    await loginPage.login(config.validUsername1, config.validPassword1);
    await page.waitForURL('**/legacy/**', { timeout: 15000 });
    await page.waitForLoadState('domcontentloaded');
  });

  test.afterAll(async () => {
    await context.close();
  });

  test('TC15: User Type and User Status accept and retain a single selected value', async () => {
    const report = new LoginStatisticsReportPage(page);

    // Step 1: Navigate to the Login Statistics Report page
    await report.navigateTo();

    // Step 2: Select company 'NTC'
    await report.selectCompany('NTC');

    // Step 3: Expand the filter accordion
    await report.expandFilter();

    // Step 4: Set User Type to 'Administrator'
    await report.setUserType('Administrator');

    // Step 5: Expect User Type value to be 'Administrator'
    await report.expectUserTypeValue('Administrator');

    // Step 6: Set User Status to 'Inactive'
    await report.setUserStatus('Inactive');

    // Step 7: Expect User Status value to be 'Inactive'
    await report.expectUserStatusValue('Inactive');
  });
});
